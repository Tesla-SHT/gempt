let language = resolveLanguage('auto');
export const locale = () => language;

function resolveLanguage(preference) {
  if (preference === 'zh' || preference === 'en') return preference;
  return /^zh/i.test(globalThis.navigator?.language || '') ? 'zh' : 'en';
}

export function tr(source, ...values) {
  const template = language === 'en' && Object.hasOwn(english, source) ? english[source] : source;
  return values.length ? template.replace(/\{(\d+)\}/g, (token, i) => values[i] ?? token) : template;
}

export function localizedFormat(Formatter, options) {
  let formatter;
  let previous;
  return {
    format(value) {
      if (previous !== language) {
        previous = language;
        formatter = new Formatter(language === 'zh' ? 'zh-CN' : 'en-US', options);
      }
      return formatter.format(value);
    },
  };
}

// Translate authored markup in place. Dynamic content is localized at its
// render sites, so user-authored text and streamed output stay untouched.
export function bindLanguage(root) {
  const bindings = [];
  const capture = (get, set) => {
    const initial = get();
    if (!initial) return;
    const source = initial.trim();
    if (!Object.hasOwn(english, source)) return;
    let expected = initial;
    bindings.push(() => {
      if (get() !== expected) return;
      expected = initial.replace(source, () => tr(source));
      if (get() !== expected) set(expected);
    });
  };
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  while (walker.nextNode()) {
    const node = walker.currentNode;
    if (!node.parentElement.closest('script, style, .language-toggle')) {
      capture(() => node.data, (value) => { node.data = value; });
    }
  }
  for (const element of root.querySelectorAll('[aria-label], [title], [placeholder]')) {
    for (const attr of ['aria-label', 'title', 'placeholder']) {
      capture(() => element.getAttribute(attr), (value) => element.setAttribute(attr, value));
    }
  }
  const apply = (preference) => {
    language = resolveLanguage(preference);
    document.documentElement.lang = language;
    for (const bind of bindings) bind();
  };
  apply('auto');
  return apply;
}


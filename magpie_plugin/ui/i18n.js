export function errorText(message) {
  if (language === 'en') return tr(message);
  if (Object.hasOwn(backendErrorsZh, message)) return backendErrorsZh[message];
  const invalid = /^Invalid ([\w.]+)\.(?: |$)/.exec(message || '');
  if (invalid) return '设置项无效（' + invalid[1] + '）';
  const status = /^HTTP (\d+)( redirect rejected)?$/.exec(message || '');
  if (status) return status[2] ? '网关重定向已拒绝（HTTP ' + status[1] + '）' : 'HTTP ' + status[1];
  const timeout = /^Timeout after (\d+)ms$/.exec(message || '');
  if (timeout) return '连接超时（' + timeout[1] + ' ms）';
  return message;
}
